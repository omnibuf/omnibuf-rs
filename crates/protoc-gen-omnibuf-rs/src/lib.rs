fn emit_encode_stmt(code: &mut String, gf: &GenField, prefix: &str, fallible: bool) {
    let fnum = gf.number;
    let access = format!("{prefix}{}", gf.rust_ident);
    let q = if fallible { "?" } else { ".unwrap()" };

    match &gf.kind {
        GenFieldKind::Scalar(s) => {
            emit_scalar_write_call(code, fnum, *s, &access);
        }
        GenFieldKind::OptScalar(s) => {
            let _ = writeln!(
                code,
                "        if let ::core::option::Option::Some(ref v) = {access} {{"
            );
            let expr = match s {
                ProtoScalar::String | ProtoScalar::Bytes => "v",
                _ => "*v",
            };
            emit_scalar_write_call(code, fnum, *s, expr);
            let _ = writeln!(code, "        }}");
        }
        GenFieldKind::SubMsg { boxed, .. } => {
            let inner = if *boxed { "&**sub" } else { "sub" };
            let _ = writeln!(
                code,
                "        if let ::core::option::Option::Some(ref sub) = {access} {{"
            );
            let _ = writeln!(
                code,
                "            ::omnibuf::codec::write_sub_msg_field(dst, {fnum}, {inner}, deterministic){q};"
            );
            let _ = writeln!(code, "        }}");
        }
        GenFieldKind::ScalarArr(s) => {
            let ewt = s.wire_type();
            let ws = scalar_elem_write_snippet(*s, "item");
            let _ = writeln!(
                code,
                "        ::omnibuf::codec::write_scalar_vec_field(dst, {fnum}, {ewt}, &{access}, |dst, item| {{ {ws} ::core::result::Result::Ok(()) }}){q};"
            );
        }
        GenFieldKind::SubMsgArr { .. } => {
            let _ = writeln!(
                code,
                "        ::omnibuf::codec::write_sub_msg_vec_field(dst, {fnum}, &{access}, deterministic){q};"
            );
        }
        GenFieldKind::Map { key, val } => {
            let kwt = key.wire_type();
            let wk = scalar_elem_write_snippet(*key, "k");
            let (vwt, wv) = match val {
                MapValKind::Scalar(vs) => (
                    vs.wire_type(),
                    format!(
                        "let _ = det; {} ::core::result::Result::Ok(())",
                        scalar_elem_write_snippet(*vs, "v")
                    ),
                ),
                MapValKind::SubMsg { .. } => (
                    WIRE_SUB_MSG,
                    "let p = dst.len(); dst.extend_from_slice(&[0, 0]); v.encode_omnibuf_append(dst, det)?; ::omnibuf::wire::backpatch_container_len(dst, p); ::core::result::Result::Ok(())".to_owned(),
                ),
            };
            let _ = writeln!(
                code,
                "        ::omnibuf::codec::write_hash_map_field(dst, {fnum}, {kwt}, {vwt}, &{access}, deterministic, |dst, k| {{ {wk} ::core::result::Result::Ok(()) }}, |dst, v, det| {{ {wv} }}){q};"
            );
        }
    }
}

fn scalar_decode_expr(scalar: ProtoScalar) -> &'static str {
    match scalar {
        ProtoScalar::Uint32 => "dec.read_uint()? as u32",
        ProtoScalar::Uint64 => "dec.read_uint()?",
        ProtoScalar::Sint32 | ProtoScalar::Enum => "dec.read_sint()? as i32",
        ProtoScalar::Sint64 => "dec.read_sint()?",
        ProtoScalar::Fixed32 => "dec.read_fixed32()?",
        ProtoScalar::Fixed64 => "dec.read_fixed64()?",
        ProtoScalar::Sfixed32 => "dec.read_sfixed32()?",
        ProtoScalar::Sfixed64 => "dec.read_sfixed64()?",
        ProtoScalar::Float32 => "dec.read_float32()?",
        ProtoScalar::Float64 => "dec.read_float64()?",
        ProtoScalar::String => "dec.read_str()?.to_owned()",
        ProtoScalar::Bytes => "dec.read_bytes()?.to_vec()",
        ProtoScalar::Bool => "wt == ::omnibuf::wire::WIRE_BOOL_TRUE",
    }
}

fn emit_decode_arm(code: &mut String, gf: &GenField, idx: usize) {
    let fnum = gf.number;
    let fident = &gf.rust_ident;

    match &gf.kind {
        GenFieldKind::Scalar(ProtoScalar::Bool) => {
            let _ = writeln!(
                code,
                "                {fnum} if wt == ::omnibuf::wire::WIRE_BOOL_FALSE || wt == ::omnibuf::wire::WIRE_BOOL_TRUE => {{ seen[{idx}] = true; self.{fident} = wt == ::omnibuf::wire::WIRE_BOOL_TRUE; }}"
            );
        }
        GenFieldKind::OptScalar(ProtoScalar::Bool) => {
            let _ = writeln!(
                code,
                "                {fnum} if wt == ::omnibuf::wire::WIRE_BOOL_FALSE || wt == ::omnibuf::wire::WIRE_BOOL_TRUE => {{ seen[{idx}] = true; self.{fident} = ::core::option::Option::Some(wt == ::omnibuf::wire::WIRE_BOOL_TRUE); }}"
            );
        }
        GenFieldKind::Scalar(s) => {
            let wt = s.wire_type();
            let expr = scalar_decode_expr(*s);
            let _ = writeln!(
                code,
                "                {fnum} if wt == {wt} => {{ seen[{idx}] = true; self.{fident} = {expr}; }}"
            );
        }
        GenFieldKind::OptScalar(s) => {
            let wt = s.wire_type();
            let expr = scalar_decode_expr(*s);
            let _ = writeln!(
                code,
                "                {fnum} if wt == {wt} => {{ seen[{idx}] = true; self.{fident} = ::core::option::Option::Some({expr}); }}"
            );
        }
        GenFieldKind::SubMsg { boxed, .. } => {
            let fn_name = if *boxed {
                "read_opt_box_sub_msg_field"
            } else {
                "read_opt_sub_msg_field"
            };
            let _ = writeln!(
                code,
                "                {fnum} if wt == {WIRE_SUB_MSG} => {{ let sub_merge = merge || seen[{idx}]; seen[{idx}] = true; let pos = dec.position(); let next_pos = ::omnibuf::codec::{fn_name}(&mut self.{fident}, dec.data(), pos, depth, sub_merge)?; dec.set_position(next_pos); }}"
            );
        }
        GenFieldKind::ScalarArr(s) => {
            let ewt = s.wire_type();
            let rs_arg = scalar_elem_read_arg(*s);
            let _ = writeln!(
                code,
                "                {fnum} if wt == {WIRE_ARRAY} => {{ let reset = !merge && !seen[{idx}]; seen[{idx}] = true; let pos = dec.position(); let next_pos = ::omnibuf::codec::read_scalar_vec_field(&mut self.{fident}, dec.data(), pos, depth, {ewt}, reset, {rs_arg})?; dec.set_position(next_pos); }}"
            );
        }
        GenFieldKind::SubMsgArr { .. } => {
            let _ = writeln!(
                code,
                "                {fnum} if wt == {WIRE_ARRAY} => {{ let reset = !merge && !seen[{idx}]; seen[{idx}] = true; let pos = dec.position(); let next_pos = ::omnibuf::codec::read_sub_msg_vec_field(&mut self.{fident}, dec.data(), pos, depth, reset)?; dec.set_position(next_pos); }}"
            );
        }
        GenFieldKind::Map { key, val } => {
            let kwt = key.wire_type();
            let rk_arg = scalar_elem_read_arg(*key);
            let (vwt, rv) = match val {
                MapValKind::Scalar(vs) => (
                    vs.wire_type(),
                    format!("|b, p, _d| {}", scalar_elem_read_snippet(*vs)),
                ),
                MapValKind::SubMsg { rust_type } => (
                    WIRE_SUB_MSG,
                    format!(
                        "|b, p, d| {{ let (sb, np) = ::omnibuf::wire::read_len_slice(b, p, 0)?; let mut sub = {rust_type}::default(); <{rust_type} as ::omnibuf::Message>::decode_omnibuf_at_depth(&mut sub, sb, d + 1, false)?; ::core::result::Result::Ok((sub, np)) }}"
                    ),
                ),
            };
            let _ = writeln!(
                code,
                "                {fnum} if wt == {WIRE_MAP} => {{ let reset = !merge && !seen[{idx}]; seen[{idx}] = true; let pos = dec.position(); let next_pos = ::omnibuf::codec::read_hash_map_field(&mut self.{fident}, dec.data(), pos, depth, {kwt}, {vwt}, reset, {rk_arg}, {rv})?; dec.set_position(next_pos); }}"
            );
        }
    }
}

fn clear_stmt_for_field(gf: &GenField) -> String {
    let fident = &gf.rust_ident;
    match &gf.kind {
        GenFieldKind::Scalar(ProtoScalar::String | ProtoScalar::Bytes)
        | GenFieldKind::ScalarArr(_)
        | GenFieldKind::SubMsgArr { .. }
        | GenFieldKind::Map { .. } => format!("self.{fident}.clear();"),
        GenFieldKind::OptScalar(_) | GenFieldKind::SubMsg { .. } => {
            format!("self.{fident} = ::core::option::Option::None;")
        }
        GenFieldKind::Scalar(_) => format!("self.{fident} = ::core::default::Default::default();"),
    }
}

fn is_heap_override(kind: &GenFieldKind) -> bool {
    !matches!(
        kind,
        GenFieldKind::Scalar(s) | GenFieldKind::OptScalar(s)
            if *s != ProtoScalar::String && *s != ProtoScalar::Bytes
    )
}

fn emit_opaque_view(code: &mut String, rust_name: &str, fields: &[GenField]) {
    let opaque_name = format!("Opaque{rust_name}");
    let heap_name = format!("Opaque{rust_name}Heap");
    let has_heap = fields.iter().any(|gf| is_heap_override(&gf.kind));
    let max_field = fields.iter().map(|f| f.number).max().unwrap_or(0);

    if has_heap {
        let _ = writeln!(code, "#[allow(dead_code)]");
        let _ = writeln!(code, "#[derive(Clone, Debug, Default)]");
        let _ = writeln!(code, "struct {heap_name} {{");
        for gf in fields {
            if is_heap_override(&gf.kind) {
                let fty = rust_field_type(&gf.kind);
                let _ = writeln!(code, "    f_{}: {fty},", gf.method_stem);
            }
        }
        let _ = writeln!(code, "}}\n");
    }

    let _ = writeln!(code, "#[allow(dead_code)]");
    let _ = writeln!(code, "#[derive(Clone, Debug, Default)]");
    let _ = writeln!(code, "pub struct {opaque_name}<'a> {{");
    let _ = writeln!(code, "    raw: ::std::borrow::Cow<'a, [u8]>,");
    let _ = writeln!(code, "    dirty: u64,");
    if has_heap {
        let _ = writeln!(
            code,
            "    heap: ::core::option::Option<::std::boxed::Box<{heap_name}>>,"
        );
    }
    for gf in fields {
        if !is_heap_override(&gf.kind) {
            let fty = rust_field_type(&gf.kind);
            let _ = writeln!(code, "    f_{}: {fty},", gf.method_stem);
        }
    }
    let _ = writeln!(code, "}}\n");

    let _ = writeln!(code, "#[allow(dead_code, clippy::too_many_arguments)]");
    let _ = writeln!(code, "impl<'a> {opaque_name}<'a> {{");
    let _ = writeln!(code, "    #[inline]");
    let _ = writeln!(code, "    pub fn new(raw: &'a [u8]) -> Self {{");
    let _ = writeln!(code, "        Self {{");
    let _ = writeln!(code, "            raw: ::std::borrow::Cow::Borrowed(raw),");
    let _ = writeln!(code, "            ..Self::default()");
    let _ = writeln!(code, "        }}");
    let _ = writeln!(code, "    }}\n");

    let _ = writeln!(code, "    #[inline]");
    let _ = writeln!(
        code,
        "    pub fn from_owned(raw: ::std::vec::Vec<u8>) -> {opaque_name}<'static> {{"
    );
    let _ = writeln!(code, "        {opaque_name} {{");
    let _ = writeln!(code, "            raw: ::std::borrow::Cow::Owned(raw),");
    let _ = writeln!(code, "            ..{opaque_name}::default()");
    let _ = writeln!(code, "        }}");
    let _ = writeln!(code, "    }}\n");

    let _ = writeln!(code, "    #[inline]");
    let _ = writeln!(code, "    pub fn unmarshal(&mut self, raw: &'a [u8]) {{");
    let _ = writeln!(
        code,
        "        self.raw = ::std::borrow::Cow::Borrowed(raw);"
    );
    let _ = writeln!(code, "        self.dirty = 0;");
    let _ = writeln!(code, "    }}\n");

    let _ = writeln!(code, "    #[inline]");
    let _ = writeln!(code, "    pub fn raw_bytes(&self) -> &[u8] {{");
    let _ = writeln!(code, "        &self.raw");
    let _ = writeln!(code, "    }}\n");

    if has_heap {
        let _ = writeln!(code, "    #[inline]");
        let _ = writeln!(code, "    fn heap_mut(&mut self) -> &mut {heap_name} {{");
        let _ = writeln!(
            code,
            "        self.heap.get_or_insert_with(::core::default::Default::default)"
        );
        let _ = writeln!(code, "    }}\n");
    }

    for gf in fields {
        emit_opaque_field_methods(code, gf);
    }

    let _ = writeln!(code, "    #[inline]");
    let _ = writeln!(code, "    pub fn marshal(&self) -> ::std::vec::Vec<u8> {{");
    let _ = writeln!(
        code,
        "        let mut dst = ::std::vec::Vec::with_capacity(self.raw.len() + 32);"
    );
    let _ = writeln!(code, "        self.marshal_append(&mut dst);");
    let _ = writeln!(code, "        dst");
    let _ = writeln!(code, "    }}\n");

    let _ = writeln!(
        code,
        "    pub fn marshal_append(&self, dst: &mut ::std::vec::Vec<u8>) {{"
    );
    let _ = writeln!(code, "        if self.dirty == 0 {{");
    let _ = writeln!(
        code,
        "            ::omnibuf::opaque::copy_packet(dst, &self.raw);"
    );
    let _ = writeln!(code, "            return;");
    let _ = writeln!(code, "        }}");
    let _ = writeln!(code, "        dst.clear();");
    let _ = writeln!(
        code,
        "        ::omnibuf::opaque::splice_fields(dst, &self.raw, self.dirty, {max_field}, |dst, fnum| {{"
    );
    let _ = writeln!(code, "            let deterministic = true;");
    let _ = writeln!(code, "            let _ = deterministic;");
    let _ = writeln!(code, "            match fnum {{");
    for gf in fields {
        let fnum = gf.number;
        let _ = writeln!(code, "                {fnum} => {{");
        emit_opaque_dirty_field(code, gf);
        let _ = writeln!(code, "                }}");
    }
    let _ = writeln!(code, "                _ => {{}}");
    let _ = writeln!(code, "            }}");
    let _ = writeln!(code, "        }});");
    let _ = writeln!(code, "    }}");
    let _ = writeln!(code, "}}\n");
}

fn emit_opaque_field_methods(code: &mut String, gf: &GenField) {
    let fnum = gf.number;
    let stem = &gf.method_stem;
    let bit = 1u64 << fnum;

    match &gf.kind {
        GenFieldKind::Scalar(ProtoScalar::String)
        | GenFieldKind::OptScalar(ProtoScalar::String) => {
            let is_opt = matches!(gf.kind, GenFieldKind::OptScalar(_));
            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn get_{stem}(&self) -> &str {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            if is_opt {
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().and_then(|h| h.f_{stem}.as_deref()).unwrap_or(\"\");"
                );
            } else {
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().map_or(\"\", |h| h.f_{stem}.as_str());"
                );
            }
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        ::omnibuf::wire::read_str(&self.raw, {fnum}).unwrap_or(\"\")"
            );
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            if is_opt {
                let _ = writeln!(
                    code,
                    "    pub fn set_{stem}(&mut self, v: ::core::option::Option<::std::string::String>) {{"
                );
                let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            } else {
                let _ = writeln!(
                    code,
                    "    pub fn set_{stem}(&mut self, v: impl ::std::convert::Into<::std::string::String>) {{"
                );
                let _ = writeln!(code, "        self.heap_mut().f_{stem} = v.into();");
            }
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::Scalar(ProtoScalar::Bytes) | GenFieldKind::OptScalar(ProtoScalar::Bytes) => {
            let is_opt = matches!(gf.kind, GenFieldKind::OptScalar(_));
            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn get_{stem}(&self) -> &[u8] {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            if is_opt {
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().and_then(|h| h.f_{stem}.as_deref()).unwrap_or(&[]);"
                );
            } else {
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().map_or(&[], |h| h.f_{stem}.as_slice());"
                );
            }
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        ::omnibuf::wire::read_bytes(&self.raw, {fnum}).unwrap_or(&[])"
            );
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            if is_opt {
                let _ = writeln!(
                    code,
                    "    pub fn set_{stem}(&mut self, v: ::core::option::Option<::std::vec::Vec<u8>>) {{"
                );
                let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            } else {
                let _ = writeln!(
                    code,
                    "    pub fn set_{stem}(&mut self, v: impl ::std::convert::Into<::std::vec::Vec<u8>>) {{"
                );
                let _ = writeln!(code, "        self.heap_mut().f_{stem} = v.into();");
            }
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::Scalar(s) | GenFieldKind::OptScalar(s) => {
            let is_opt = matches!(gf.kind, GenFieldKind::OptScalar(_));
            let rty = s.rust_type();
            let read_call = match s {
                ProtoScalar::Uint32 => {
                    format!("::omnibuf::wire::read_uint(&self.raw, {fnum}).unwrap_or(0) as u32")
                }
                ProtoScalar::Uint64 => {
                    format!("::omnibuf::wire::read_uint(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Sint32 | ProtoScalar::Enum => {
                    format!("::omnibuf::wire::read_sint(&self.raw, {fnum}).unwrap_or(0) as i32")
                }
                ProtoScalar::Sint64 => {
                    format!("::omnibuf::wire::read_sint(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Bool => {
                    format!("::omnibuf::wire::read_bool(&self.raw, {fnum}).unwrap_or(false)")
                }
                ProtoScalar::Fixed32 => {
                    format!("::omnibuf::wire::read_fixed32(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Fixed64 => {
                    format!("::omnibuf::wire::read_fixed64(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Sfixed32 => {
                    format!("::omnibuf::wire::read_sfixed32(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Sfixed64 => {
                    format!("::omnibuf::wire::read_sfixed64(&self.raw, {fnum}).unwrap_or(0)")
                }
                ProtoScalar::Float32 => {
                    format!("::omnibuf::wire::read_float32(&self.raw, {fnum}).unwrap_or(0.0)")
                }
                ProtoScalar::Float64 => {
                    format!("::omnibuf::wire::read_float64(&self.raw, {fnum}).unwrap_or(0.0)")
                }
                ProtoScalar::String | ProtoScalar::Bytes => unreachable!(),
            };

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn get_{stem}(&self) -> {rty} {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            if is_opt {
                let _ = writeln!(
                    code,
                    "            return self.f_{stem}.unwrap_or_default();"
                );
            } else {
                let _ = writeln!(code, "            return self.f_{stem};");
            }
            let _ = writeln!(code, "        }}");
            let _ = writeln!(code, "        {read_call}");
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            if is_opt {
                let _ = writeln!(
                    code,
                    "    pub fn set_{stem}(&mut self, v: ::core::option::Option<{rty}>) {{"
                );
            } else {
                let _ = writeln!(code, "    pub fn set_{stem}(&mut self, v: {rty}) {{");
            }
            let _ = writeln!(code, "        self.f_{stem} = v;");
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::SubMsg { rust_type, boxed } => {
            let sub_opaque = format!("Opaque{rust_type}");
            let set_ty = rust_field_type(&gf.kind);
            let deref_sub = if *boxed { "&**sub" } else { "sub" };

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn get_{stem}(&self) -> {sub_opaque}<'_> {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            let _ = writeln!(
                code,
                "            if let ::core::option::Option::Some(ref sub) = self.heap.as_deref().unwrap().f_{stem} {{"
            );
            let _ = writeln!(
                code,
                "                return {sub_opaque}::from_owned(({deref_sub}).marshal_omnibuf());"
            );
            let _ = writeln!(code, "            }}");
            let _ = writeln!(code, "            return {sub_opaque}::new(&[]);");
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        match ::omnibuf::wire::read_sub_msg(&self.raw, {fnum}) {{"
            );
            let _ = writeln!(
                code,
                "            ::core::option::Option::Some(cow) => {sub_opaque} {{ raw: cow, ..{sub_opaque}::default() }},"
            );
            let _ = writeln!(
                code,
                "            ::core::option::Option::None => {sub_opaque}::new(&[]),"
            );
            let _ = writeln!(code, "        }}");
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn set_{stem}(&mut self, v: {set_ty}) {{");
            let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::ScalarArr(s) => {
            let ewt = s.wire_type();
            let elem_ty = s.rust_type();
            let rs = scalar_elem_read_snippet(*s);

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn {stem}_len(&self) -> usize {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            let _ = writeln!(
                code,
                "            return self.heap.as_deref().map_or(0, |h| h.f_{stem}.len());"
            );
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        ::omnibuf::wire::counted_arr_len(&self.raw, {fnum}, {ewt})"
            );
            let _ = writeln!(code, "    }}");

            let _ = writeln!(
                code,
                "    pub fn get_{stem}(&self) -> ::std::vec::Vec<{elem_ty}> {{"
            );
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            let _ = writeln!(
                code,
                "            return self.heap.as_deref().map_or_else(::std::vec::Vec::new, |h| h.f_{stem}.clone());"
            );
            let _ = writeln!(code, "        }}");
            let _ = writeln!(code, "        let mut out = ::std::vec::Vec::new();");
            let _ = writeln!(code, "        let mut pos = 0usize;");
            let _ = writeln!(code, "        loop {{");
            let _ = writeln!(
                code,
                "            let (matched, valid) = ::omnibuf::wire::next_container_field(&self.raw, pos, {fnum}, {WIRE_ARRAY}, 2, false);"
            );
            let _ = writeln!(
                code,
                "            if !valid {{ return ::std::vec::Vec::new(); }}"
            );
            let _ = writeln!(
                code,
                "            let ::core::option::Option::Some((body, next_pos)) = matched else {{ return out; }};"
            );
            let _ = writeln!(
                code,
                "            let ::core::option::Option::Some((e, count, mut p)) = ::omnibuf::wire::parse_array_header(body) else {{ return ::std::vec::Vec::new(); }};"
            );
            let _ = writeln!(
                code,
                "            if e != {ewt} {{ return ::std::vec::Vec::new(); }}"
            );
            let _ = writeln!(code, "            out.reserve(count);");
            let _ = writeln!(code, "            let b = body;");
            let _ = writeln!(code, "            for _ in 0..count {{");
            let _ = writeln!(
                code,
                "                let ::core::result::Result::Ok((val, np)) = {rs} else {{ return ::std::vec::Vec::new(); }};"
            );
            let _ = writeln!(code, "                out.push(val);");
            let _ = writeln!(code, "                p = np;");
            let _ = writeln!(code, "            }}");
            let _ = writeln!(
                code,
                "            if p != body.len() {{ return ::std::vec::Vec::new(); }}"
            );
            let _ = writeln!(code, "            pos = next_pos;");
            let _ = writeln!(code, "        }}");
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(
                code,
                "    pub fn set_{stem}(&mut self, v: ::std::vec::Vec<{elem_ty}>) {{"
            );
            let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::SubMsgArr { rust_type } => {
            let sub_opaque = format!("Opaque{rust_type}");
            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn {stem}_len(&self) -> usize {{");
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            let _ = writeln!(
                code,
                "            return self.heap.as_deref().map_or(0, |h| h.f_{stem}.len());"
            );
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        ::omnibuf::wire::sub_msg_arr_len(&self.raw, {fnum})"
            );
            let _ = writeln!(code, "    }}");

            let _ = writeln!(
                code,
                "    pub fn get_{stem}(&self, idx: usize) -> {sub_opaque}<'_> {{"
            );
            let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
            let _ = writeln!(
                code,
                "            if let ::core::option::Option::Some(elem) = self.heap.as_deref().and_then(|h| h.f_{stem}.get(idx)) {{"
            );
            let _ = writeln!(
                code,
                "                return {sub_opaque}::from_owned(elem.marshal_omnibuf());"
            );
            let _ = writeln!(code, "            }}");
            let _ = writeln!(code, "            return {sub_opaque}::new(&[]);");
            let _ = writeln!(code, "        }}");
            let _ = writeln!(
                code,
                "        match ::omnibuf::wire::read_sub_msg_arr_elem(&self.raw, {fnum}, idx) {{"
            );
            let _ = writeln!(
                code,
                "            ::core::option::Option::Some(slice) => {sub_opaque}::new(slice),"
            );
            let _ = writeln!(
                code,
                "            ::core::option::Option::None => {sub_opaque}::new(&[]),"
            );
            let _ = writeln!(code, "        }}");
            let _ = writeln!(code, "    }}");

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(
                code,
                "    pub fn set_{stem}(&mut self, v: ::std::vec::Vec<{rust_type}>) {{"
            );
            let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
        GenFieldKind::Map { key, val } => {
            let map_ty = rust_field_type(&gf.kind);
            if *key == ProtoScalar::String
                && matches!(
                    val,
                    MapValKind::Scalar(ProtoScalar::Uint64 | ProtoScalar::Uint32)
                )
            {
                let vty = match val {
                    MapValKind::Scalar(vs) => vs.rust_type(),
                    _ => "u64",
                };
                let _ = writeln!(code, "    #[inline]");
                let _ = writeln!(
                    code,
                    "    pub fn lookup_{stem}(&self, key: &str) -> ::core::option::Option<{vty}> {{"
                );
                let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().and_then(|h| h.f_{stem}.get(key).copied());"
                );
                let _ = writeln!(code, "        }}");
                if matches!(val, MapValKind::Scalar(ProtoScalar::Uint64)) {
                    let _ = writeln!(
                        code,
                        "        ::omnibuf::wire::lookup_map_string_uint(&self.raw, {fnum}, key)"
                    );
                } else {
                    let _ = writeln!(
                        code,
                        "        ::omnibuf::wire::lookup_map_string_uint(&self.raw, {fnum}, key).map(|v| v as {vty})"
                    );
                }
                let _ = writeln!(code, "    }}");
            }

            if *key == ProtoScalar::String && matches!(val, MapValKind::Scalar(ProtoScalar::Uint64))
            {
                let _ = writeln!(code, "    pub fn get_{stem}(&self) -> {map_ty} {{");
                let _ = writeln!(code, "        if (self.dirty & {bit}u64) != 0 {{");
                let _ = writeln!(
                    code,
                    "            return self.heap.as_deref().map_or_else(::core::default::Default::default, |h| h.f_{stem}.clone());"
                );
                let _ = writeln!(code, "        }}");
                let _ = writeln!(
                    code,
                    "        ::omnibuf::wire::read_map_string_uint(&self.raw, {fnum}).unwrap_or_default()"
                );
                let _ = writeln!(code, "    }}");
            }

            let _ = writeln!(code, "    #[inline]");
            let _ = writeln!(code, "    pub fn set_{stem}(&mut self, v: {map_ty}) {{");
            let _ = writeln!(code, "        self.heap_mut().f_{stem} = v;");
            let _ = writeln!(code, "        self.dirty |= {bit}u64;");
            let _ = writeln!(code, "    }}\n");
        }
    }
}

fn emit_opaque_dirty_field(code: &mut String, gf: &GenField) {
    let prefix = if is_heap_override(&gf.kind) {
        "self.heap.as_deref().unwrap()."
    } else {
        "self."
    };
    let temp = GenField {
        number: gf.number,
        proto_name: gf.proto_name.clone(),
        rust_ident: format!("f_{}", gf.method_stem),
        method_stem: gf.method_stem.clone(),
        kind: match &gf.kind {
            GenFieldKind::Scalar(s) => GenFieldKind::Scalar(*s),
            GenFieldKind::OptScalar(s) => GenFieldKind::OptScalar(*s),
            GenFieldKind::SubMsg { rust_type, boxed } => GenFieldKind::SubMsg {
                rust_type: rust_type.clone(),
                boxed: *boxed,
            },
            GenFieldKind::ScalarArr(s) => GenFieldKind::ScalarArr(*s),
            GenFieldKind::SubMsgArr { rust_type } => GenFieldKind::SubMsgArr {
                rust_type: rust_type.clone(),
            },
            GenFieldKind::Map { key, val } => GenFieldKind::Map {
                key: *key,
                val: match val {
                    MapValKind::Scalar(vs) => MapValKind::Scalar(*vs),
                    MapValKind::SubMsg { rust_type } => MapValKind::SubMsg {
                        rust_type: rust_type.clone(),
                    },
                },
            },
        },
    };
    emit_encode_stmt(code, &temp, prefix, false);
}

fn to_pascal_case(s: &str) -> String {
    let all_shouty = s.chars().all(|c| !c.is_lowercase());
    let mut out = String::with_capacity(s.len());
    let mut upper_next = true;
    for ch in s.chars() {
        if ch == '_' || ch == '-' || ch == '.' {
            upper_next = true;
        } else if upper_next {
            for up in ch.to_uppercase() {
                out.push(up);
            }
            upper_next = false;
        } else if all_shouty {
            for lo in ch.to_lowercase() {
                out.push(lo);
            }
        } else {
            out.push(ch);
        }
    }
    out
}

fn to_snake_case(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    let chars: Vec<char> = s.chars().collect();
    for (i, &ch) in chars.iter().enumerate() {
        if ch == '-' || ch == '.' {
            out.push('_');
            continue;
        }
        if ch.is_uppercase() {
            let prev_lower = i > 0 && chars[i - 1].is_lowercase();
            let next_lower =
                i + 1 < chars.len() && chars[i + 1].is_lowercase() && i > 0 && chars[i - 1] != '_';
            if prev_lower || next_lower {
                out.push('_');
            }
            for lo in ch.to_lowercase() {
                out.push(lo);
            }
        } else {
            out.push(ch);
        }
    }
    out
}

fn escape_rust_ident(s: &str) -> String {
    match s {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "gen" | "macro" | "override"
        | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try" => format!("r#{s}"),
        _ => s.to_owned(),
    }
}
